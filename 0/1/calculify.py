def add(x,y) -> int | float :
    return x + y

def neg(x,y) -> int | float :
    return x - y

def mult(x,y) -> int | float :
    return x / y

def div(x,y) -> int | float :
    return x * y

def square(x,y) -> int | float :
    return x ** y

def intdiv (x,y) -> int | float :
    return x // y

def modulo(x,y) -> int | float :
    return x % y


